"""Generate firmware/src/rift_tables.h: every number RIFT needs that would take floating point
on the FM-1 (it has no FPU). Run: python3 tools/gen_rift_tables.py"""
import math
from pathlib import Path

FS = 44100
FO = FS * 2                      # oversampled core
OUT = Path(__file__).resolve().parents[1] / "firmware" / "src" / "rift_tables.h"
L = []


RAM_TABLES = {"TANH_T", "SIN_T", "HB_T", "DUCK_DB_T", "G_BR_T"}   # read every sample: in RAM (.data), not through the XIP cache


def arr(name, vals, ctype="int32_t", per=8):
    if name in RAM_TABLES:      # (the section: without it the optimiser sees no store and makes it a constant again)
        L.append(f"static {ctype} {name}[{len(vals)}] __attribute__((section(\".data.rtab\"))) = {{")
    else:
        L.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        L.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    L.append("};")


def define(name, v):
    L.append(f"#define {name} {int(round(v))}")


Q24, Q30, Q16 = 1 << 24, 1 << 30, 1 << 16
clampi = lambda v, a, b: max(a, min(b, v))

L.append("/* generated by tools/gen_rift_tables.py: do not edit */")
L.append("#ifndef RIFT_TABLES_H\n#define RIFT_TABLES_H")

# tanh over [-8, 8], 1024 steps (1/64), Q24
arr("TANH_T", [round(math.tanh(-8 + i / 64) * Q24) for i in range(1025)])
# sine over one cycle, 1024 steps, Q24 (+1 guard)
arr("SIN_T", [round(math.sin(2 * math.pi * i / 1024) * Q24) for i in range(1025)])
# 2^(k/768), Q30 (1/64 semitone inside an octave)
arr("EXP2_T", [min(2**31 - 1, round(2 ** (k / 768) * Q30)) for k in range(769)])
# phase increment of C-1 (MIDI 0, 8.1758 Hz) at the core rate FO, as Q32 phase per sample, scaled by 2^8 for precision
define("INC_C0_OS_Q40", 440 * 2 ** (-69 / 12) / FO * 2 ** 40)
define("INC_C0_BR_Q40", 440 * 2 ** (-69 / 12) / FS * 2 ** 40)


# cutoff index c: fc = 20 * 2^(c/64) Hz, c = 0..704 (11 octaves: 20 Hz .. 40 kHz)
def fc_of(c):
    return 20 * 2 ** (c / 64)


NC = 705
G_OS = []
SVF_A1, SVF_A2, SVF_A3 = [], [], []
K_BW = math.sqrt(2)
for c in range(NC):
    f = min(fc_of(c), 0.42 * FO)
    g = math.tan(math.pi * f / FO)
    G_OS.append(round(g / (1 + g) * Q30))
    a1 = 1 / (1 + g * (g + K_BW))
    SVF_A1.append(round(a1 * Q30)); SVF_A2.append(round(g * a1 * Q30)); SVF_A3.append(round(g * g * a1 * Q30))
arr("G_OS_T", G_OS)
arr("SVF_A1_T", SVF_A1); arr("SVF_A2_T", SVF_A2); arr("SVF_A3_T", SVF_A3)
define("K_BW_Q30", K_BW * Q30)
G_BR = []
for c in range(NC):
    f = min(fc_of(c), 0.45 * FS)
    g = math.tan(math.pi * f / FS)
    G_BR.append(round(g / (1 + g) * Q30))
arr("G_BR_T", G_BR)
SB1, SB2, SB3 = [], [], []          # the same SVF at the base rate (the linear stages after the decimator)
for c in range(NC):
    f = min(fc_of(c), 0.45 * FS)
    g = math.tan(math.pi * f / FS)
    a1 = 1 / (1 + g * (g + K_BW))
    SB1.append(round(a1 * Q30)); SB2.append(round(g * a1 * Q30)); SB3.append(round(g * g * a1 * Q30))
arr("SVFB_A1_T", SB1); arr("SVFB_A2_T", SB2); arr("SVFB_A3_T", SB3)


def cidx(f):
    return round(64 * math.log2(f / 20))


for name, f in [("CI_120", 120), ("CI_150", 150), ("CI_40", 40), ("CI_100", 100), ("CI_720", 720), ("CI_9K", 9000),
                ("CI_250", 250), ("CI_3K2", 3200), ("CI_20", 20), ("CI_7K", 7000), ("CI_160", 160), ("CI_700", 700), ("CI_55", 55), ("CI_28", 28)]:
    define(name, cidx(f))

# ladder passband compensation sqrt(1 + min(k,4)), k = 0..5 in 1/64 steps, Q16
arr("LCOMP_T", [round(math.sqrt(1 + min(k / 64, 4)) * Q16) for k in range(5 * 64 + 1)])

# BURST macro: 65 steps of x = 0..1, piecewise linear between the five anchors
BT = dict(pre=[0, 2, 5, 8, 12], bias=[0, .03, .07, .11, .15], fold=[0, 0, .15, .45, 1.0], gain=[0, 9, 18, 25, 32],
          wet=[0, .5, 1, 1, 1], chr=[0, 0, 1, 1.5, 2], hump=[0, 2, 4, 6, 7], cab=[12000, 10000, 7500, 5500, 4500],
          ott=[0, .1, .3, .6, .9], low=[0, .5, 1, 1.5, 2], sub=[0, 1, 2, 3, 3], comp=[0, -2, -5, -7, -9], post=[0, -.5, -1.2, -1.5, -2])


def tab5(t, x):
    f = min(1, max(0, x)) * 4
    i = min(3, int(f))
    return t[i] + (t[i + 1] - t[i]) * (f - i)


db = lambda d: 10 ** (d / 20)
B = {k: [] for k in ["preG", "preGA", "bias", "fold", "gain", "wet", "chr", "hump", "cabc", "ott", "low", "sub", "comp", "post"]}
for i in range(65):
    x = i / 64
    B["preG"].append(round(db(tab5(BT["pre"], x)) * Q16))
    B["preGA"].append(round(db(min(6, tab5(BT["pre"], x))) * Q16))
    B["bias"].append(round(tab5(BT["bias"], x) * Q24))
    B["fold"].append(round(tab5(BT["fold"], x) * Q16))
    B["gain"].append(round(db(tab5(BT["gain"], x)) * 1.4 * Q16))
    B["wet"].append(round(tab5(BT["wet"], x) * Q16))
    B["chr"].append(round(tab5(BT["chr"], x) * Q16))
    B["hump"].append(round((db(tab5(BT["hump"], x)) - 1) * Q16))
    B["cabc"].append(cidx(tab5(BT["cab"], x)))
    B["ott"].append(round(tab5(BT["ott"], x) * Q16))
    B["low"].append(round(db(tab5(BT["low"], x)) * Q16))
    B["sub"].append(round(db(tab5(BT["sub"], x)) * Q16))
    B["comp"].append(round(db(tab5(BT["comp"], x)) * Q16))
    B["post"].append(round(db(tab5(BT["post"], x)) * Q16))
for k, v in B.items():
    arr("BT_" + k.upper(), v)


def kexp(tau_s, fs=FS):
    return round(math.exp(-1 / (fs * tau_s)) * Q30)


# filter env decay (303 mapping): 200..2000 ms, 256 steps; tau = t/3
arr("KF_ACID_T", [kexp(0.2 * 10 ** (i / 255) / 3) for i in range(256)])
# filter env decay for the other engines: 80..2000 ms
arr("KF_WIDE_T", [kexp(0.08 * 25 ** (i / 255) / 3) for i in range(256)])
define("KF_ACC", kexp(0.2 / 3))
define("K_ACCENV", kexp(0.067))
define("K_AMPHOLD", kexp(3.0))
define("ATT_F_STEP", Q24 / (0.003 * FS))     # filter env attack 3 ms (Q24 per sample)
define("ATT_A_STEP", Q24 / (0.001 * FS))     # amp attack 1 ms
arr("K_REL_T", [kexp((1 + i * 199 / 63) / 1000 / 3) for i in range(64)])   # amp release 1..200 ms
arr("K_GLIDE_T", [kexp(0.025 + 0.09 * i / 63) for i in range(64)])
# accent capacitor: charge / discharge time against resonance (64 steps)
arr("K_CAPC_T", [round((1 - math.exp(-1 / (FS * (0.002 + 0.043 * i / 63)))) * Q30) for i in range(64)])
arr("K_CAPD_T", [round((1 - math.exp(-1 / (FS * (0.03 + 0.19 * i / 63)))) * Q30) for i in range(64)])
arr("K_KICK_T", [kexp(0.08 + 0.3 * i / 63) for i in range(64)])
arr("K_DUCK_T", [kexp((0.15 + 0.1 * (1 - i / 63)) / 2.2) for i in range(64)])
define("K_KICKP", kexp(1 / (44100 * (1 - 0.9993))))
define("K_CLICK", round(0.97 * Q30))
define("K_HAT", round(0.9985 * Q30))
define("K_RMS", round(0.0005 * Q30))
# dB -> linear for the duck: -0.25 dB steps down to -48 dB (193 entries), Q16
arr("DUCK_DB_T", [round(db(-i / 4) * Q16) for i in range(193)])

# 2x -> 1x halfband (47 taps, Kaiser beta 8), Q30
N, beta = 47, 8.0


def i0(x):
    s, t = 1.0, 1.0
    for k in range(1, 30):
        t *= (x / (2 * k)) ** 2
        s += t
    return s


M = (N - 1) / 2
h = []
for n in range(N):
    m = n - M
    sinc = 1 if m == 0 else math.sin(math.pi * 0.5 * m) / (math.pi * 0.5 * m)
    w = i0(beta * math.sqrt(1 - (m / M) ** 2)) / i0(beta)
    h.append(0.5 * sinc * w)
s = sum(h)
h = [x / s for x in h]
arr("HB_T", [round(x * Q30) for x in h])
define("HB_N", N)

# crack tree for the 240 x 122 scope (x1 y1 x2 y2 threshold(0..255) width)
import random
rnd = random.Random(0x0C0FFEE5)
segs = []


def grow(x, y, ang, ln, t, depth):
    if depth > 6 or ln < 3:
        return
    n = 2 + rnd.randint(0, 2)
    for _ in range(n):
        a = ang + (rnd.random() - 0.5) * 0.9
        l = ln * (0.5 + rnd.random() * 0.5)
        x2, y2 = x + math.cos(a) * l, y + math.sin(a) * l
        t2 = t + 0.05 + rnd.random() / 11
        segs.append((x, y, x2, y2, t2, max(1, 2 - depth * 0.35)))
        x, y = x2, y2
        if rnd.random() < 0.45:
            grow(x, y, a + (0.9 if rnd.random() < 0.5 else -0.9), l * 0.8, t2, depth + 1)


grow(240, 2, math.pi * 0.82, 23, 0, 0); grow(2, 118, -math.pi * 0.18, 20, 0.18, 1)
grow(150, 0, math.pi * 0.62, 17, 0.32, 1); grow(60, 122, -math.pi * 0.42, 15, 0.45, 2)
segs = [s for s in segs if s[4] < 1.0][:160]
flat = []
for x1, y1, x2, y2, t, w in segs:
    flat += [clampi(round(x1), 0, 239), clampi(round(y1), 0, 121), clampi(round(x2), 0, 239), clampi(round(y2), 0, 121), clampi(round(t * 255), 0, 255), round(w)]
arr("CRACK_T", flat, "uint8_t", 12)
define("NCRACK", len(segs))

# glyphs: 爆 and 裂, 1-bit bitmaps (row-major, MSB first)
from PIL import Image, ImageDraw, ImageFont
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Black.ttc"
for ch, nm in [("爆", "BAO"), ("裂", "LIE")]:
    for sz in (16, 32):
        f = ImageFont.truetype(FONT, int(sz * 1.0), index=0)
        im = Image.new("L", (sz, sz), 0)
        d = ImageDraw.Draw(im)
        bb = d.textbbox((0, 0), ch, font=f)
        d.text(((sz - (bb[2] - bb[0])) / 2 - bb[0], (sz - (bb[3] - bb[1])) / 2 - bb[1]), ch, fill=255, font=f)
        bits = []
        for y in range(sz):
            row = 0
            for x in range(sz):
                row = row << 1 | (1 if im.getpixel((x, y)) > 110 else 0)
            bits.append(row)
        arr(f"GLYPH_{nm}{sz}", bits, "uint32_t", 8)

L.append("#endif")
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT, sum(1 for l in L), "lines")
